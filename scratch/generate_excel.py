def create_score_sheet(ws, title, items, price_weight):
    ws.title = title
    headers = ['评审大项', '评审子项', '评分点', '分值', '评分标准', '供应商A原始分', '供应商B原始分', '供应商C原始分', '备注/评分依据']
    for col, header in enumerate(headers, start=1):
        cell = ws.cell(1, col, header)
        cell.fill = header_fill
        cell.font = header_font
        cell.alignment = center
        cell.border = border

    start_row = 2
    for index, (category, sub_item, point, score, rule) in enumerate(items, start=start_row):
        ws.cell(index, 1, category)
        ws.cell(index, 2, sub_item)
        ws.cell(index, 3, point)
        ws.cell(index, 4, score)
        ws.cell(index, 5, rule)
        if sub_item == '报价得分':
            ws.cell(index, 6, f'=IFERROR(MIN($K$2:$M$2)/K2*{price_weight},0)')
            ws.cell(index, 7, f'=IFERROR(MIN($K$2:$M$2)/L2*{price_weight},0)')
            ws.cell(index, 8, f'=IFERROR(MIN($K$2:$M$2)/M2*{price_weight},0)')
        fill = sub_fill if index % 2 == 0 else PatternFill('solid', fgColor='FFFFFF')
        for col in range(1, 10):
            ws.cell(index, col).fill = fill

    total_row = start_row + len(items)
    ws.cell(total_row, 1, '合计')
    ws.cell(total_row, 4, 100)
    ws.cell(total_row, 6, f'=SUM(F{start_row}:F{total_row - 1})')
    ws.cell(total_row, 7, f'=SUM(G{start_row}:G{total_row - 1})')
    ws.cell(total_row, 8, f'=SUM(H{start_row}:H{total_row - 1})')
    for col in range(1, 10):
        ws.cell(total_row, col).fill = section_fill
        ws.cell(total_row, col).font = sub_font

    score_input_end = total_row - 1
    for col in range(6, 9):
        col_letter = get_column_letter(col)
        for row in range(start_row, score_input_end + 1):
            if ws.cell(row, 2).value == '报价得分':
                continue
            dv_row = DataValidation(
                type='decimal',
                operator='between',
                formula1='0',
                formula2=f'$D${row}',
                allow_blank=True,
            )
            dv_row.error = f'请输入0到D{row}之间的分数，且不得超过本行分值。'
            dv_row.errorTitle = '分值输入有误'
            ws.add_data_validation(dv_row)
            dv_row.add(ws.cell(row, col))
            ws.conditional_formatting.add(
                f'{col_letter}{row}',
                FormulaRule(formula=[f'{col_letter}{row}>$D${row}'], stopIfTrue=True, fill=warn_fill)
            )

    ws['K1'] = '供应商A有效报价'
    ws['L1'] = '供应商B有效报价'
    ws['M1'] = '供应商C有效报价'
    ws['K2'] = 100
    ws['L2'] = 120
    ws['M2'] = 110
    for col in range(11, 14):
        ws.cell(1, col).fill = warn_fill
        ws.cell(1, col).font = sub_font
        ws.cell(1, col).alignment = center
        ws.cell(2, col).border = border

    style_range(ws, 1, total_row, 9)
    set_widths(ws, [18, 18, 28, 10, 55, 14, 14, 14, 24, 4, 16, 16, 16])
    ws.freeze_panes = 'A2'


