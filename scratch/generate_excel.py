def style_range(ws, start_row, end_row, end_col):
    for r in range(start_row, end_row + 1):
        for c in range(1, end_col + 1):
            cell = ws.cell(r, c)
            cell.border = border
            cell.alignment = center if c not in (2, 3, 5, 9) else left


